/**
 * pdfReportGenerator.js
 * Utility to generate weekly progress PDF reports for rural classroom analytics.
 * Outputs a plain-text PDF-like structure using basic Buffer encoding.
 * Production usage should swap the body builder with a library like PDFKit.
 *
 * Sprint Week 13 (Nov 6-12, 2026) — Rishabh Jain
 */

const path = require('path');
const fs = require('fs');

const REPORTS_DIR = path.join(__dirname, '..', '..', 'weekly_reports');

/**
 * Pad a string to a fixed column width.
 * @param {string} str
 * @param {number} width
 * @returns {string}
 */
function padCol(str, width) {
  const s = String(str ?? '');
  return s.length >= width ? s.slice(0, width) : s + ' '.repeat(width - s.length);
}

/**
 * Build a simple ASCII table from an array of row objects.
 * @param {string[]} headers
 * @param {Object[]} rows
 * @param {number[]} colWidths
 * @returns {string}
 */
function buildTable(headers, rows, colWidths) {
  const separator = colWidths.map(w => '-'.repeat(w)).join('-+-');
  const headerRow = headers.map((h, i) => padCol(h, colWidths[i])).join(' | ');
  const bodyRows = rows.map(row =>
    headers.map((h, i) => padCol(row[h] ?? '', colWidths[i])).join(' | ')
  );
  return [headerRow, separator, ...bodyRows].join('\n');
}

/**
 * Generate a weekly PDF-compatible text report and save it to disk.
 *
 * @param {Object} opts
 * @param {string}   opts.weekLabel      e.g. "2026-11-06"
 * @param {string}   opts.className      e.g. "CSE-A 3rd Year"
 * @param {Object[]} opts.attendanceRows Array of { name, present, total, percentage }
 * @param {Object[]} opts.quizRows       Array of { name, quiz, score, maxScore, grade }
 * @param {Object}   opts.summary        { avgAttendance, avgScore, topStudent }
 * @returns {string} Absolute file path of the generated report
 */
function generateWeeklyReport({ weekLabel, className, attendanceRows = [], quizRows = [], summary = {} }) {
  if (!fs.existsSync(REPORTS_DIR)) {
    fs.mkdirSync(REPORTS_DIR, { recursive: true });
  }

  const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
  const fileName = `SKIT-CSE-2023-2027-39_Weekly_Progress_Report_Form-3_${weekLabel}.pdf`;
  const filePath = path.join(REPORTS_DIR, fileName);

  const header = [
    '='.repeat(72),
    `  SKIT — Remote Classroom Weekly Progress Report`,
    `  Class       : ${className}`,
    `  Week        : ${weekLabel}`,
    `  Generated   : ${new Date().toUTCString()}`,
    '='.repeat(72),
    '',
  ].join('\n');

  const attendanceSection = [
    'SECTION A: ATTENDANCE',
    '-'.repeat(72),
    buildTable(
      ['name', 'present', 'total', 'percentage'],
      attendanceRows,
      [24, 10, 10, 12]
    ),
    '',
    `  Average Attendance : ${summary.avgAttendance ?? 'N/A'}%`,
    '',
  ].join('\n');

  const quizSection = [
    'SECTION B: QUIZ PERFORMANCE',
    '-'.repeat(72),
    buildTable(
      ['name', 'quiz', 'score', 'maxScore', 'grade'],
      quizRows,
      [20, 24, 8, 10, 8]
    ),
    '',
    `  Average Score : ${summary.avgScore ?? 'N/A'}`,
    `  Top Student   : ${summary.topStudent ?? 'N/A'}`,
    '',
  ].join('\n');

  const footer = [
    '='.repeat(72),
    '  END OF REPORT — Generated by Remote Classroom Analytics System',
    '='.repeat(72),
  ].join('\n');

  const content = [header, attendanceSection, quizSection, footer].join('\n');
  fs.writeFileSync(filePath, content, 'utf8');

  console.log(`[pdfReportGenerator] Report saved → ${filePath}`);
  return filePath;
}

/**
 * Express route handler: POST /api/analytics/generate-report
 * Body: { weekLabel, className, attendanceRows, quizRows, summary }
 */
async function handleGenerateReport(req, res) {
  try {
    const { weekLabel, className, attendanceRows, quizRows, summary } = req.body;
    if (!weekLabel || !className) {
      return res.status(400).json({ error: 'weekLabel and className are required' });
    }
    const filePath = generateWeeklyReport({ weekLabel, className, attendanceRows, quizRows, summary });
    const fileName = path.basename(filePath);
    res.json({ success: true, fileName, filePath });
  } catch (err) {
    console.error('[handleGenerateReport]', err);
    res.status(500).json({ error: 'Failed to generate report', details: err.message });
  }
}

module.exports = { generateWeeklyReport, handleGenerateReport, buildTable };
